#!/usr/bin/env bun
/**
 * Regenerate `src/lib/qrcode/logo.ts` from `public/logo.svg`.
 *
 * `public/logo.svg` is the dark line-art path followed by an opaque light path
 * that fills the rest of the 1024×1024 square. The QR code wants only the line
 * art on a transparent background (an opaque square would paint over the
 * surrounding dots), so this keeps the first path and drops the rest.
 *
 * Usage: bun run qr-logo
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const source = readFileSync(join(root, "public", "logo.svg"), "utf8");

const viewBox = /viewBox="([^"]+)"/.exec(source)?.[1];
const lineArt = /<path d="([^"]+)" fill="([^"]+)"\s*\/>/.exec(source);
if (!viewBox || !lineArt) {
  console.error("public/logo.svg no longer has the expected viewBox + first <path d fill> shape.");
  process.exit(1);
}

const [, d, fill] = lineArt;
const rgb = /rgb\((\d+),\s*(\d+),\s*(\d+)\)/.exec(fill);
if (rgb && Math.min(...rgb.slice(1).map(Number)) > 200) {
  console.error(`The first <path> in public/logo.svg is ${fill}, a light colour; expected the dark line art.`);
  process.exit(1);
}
const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">` +
  `<path d="${d}" fill="${fill}"/></svg>`;

writeFileSync(
  join(root, "src", "lib", "qrcode", "logo.ts"),
  `/**
 * ViewPet logo as a transparent-background \`data:\` URI, inlined so QR rendering
 * never depends on \`public/\` being present on the server's disk.
 *
 * GENERATED by scripts/build-qr-logo.ts from public/logo.svg — do not edit;
 * run \`bun run qr-logo\` after changing the logo.
 */
export const LOGO_DATA_URI =
  "data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}";
`,
);
console.log("Wrote src/lib/qrcode/logo.ts");
